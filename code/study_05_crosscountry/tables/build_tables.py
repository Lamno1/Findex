def pp(x, d: int = 3) -> str:
    """Percentage points, d decimals."""
    return f"{100.0 * float(x):.{d}f}"


def num(x, d: int = 3) -> str:
    return f"{float(x):.{d}f}"


def pval(p) -> str:
    if p in (None, "", "nan") or (isinstance(p, float) and math.isnan(p)):
        return "--"
    p = float(p)
    if p < 1e-4:
        return "$<$0.0001"
    if p < 0.001:
        return f"{p:.5f}"
    return f"{p:.3f}"


def stars(p) -> str:
    if p in (None, "", "nan"):
        return ""
    p = float(p)
    return "***" if p < 0.01 else "**" if p < 0.05 else "*" if p < 0.10 else ""


def se_line(se, d: int = 3) -> str:
    return f"({100.0 * float(se):.{d}f})"


def ci(lo, hi, d: int = 2) -> str:
    return f"[{100.0*float(lo):.{d}f}, {100.0*float(hi):.{d}f}]"


def intfmt(n) -> str:
    return f"{int(round(float(n))):,}"


