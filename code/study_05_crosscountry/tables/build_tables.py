def write(name: str, body: str) -> None:
    # threeparttable ties its notes to the (possibly very wide) natural table width,
    # which overflows the text block. Replace it with: adjustbox around the tabular
    # (shrinks only when needed) + a full-width minipage for the notes.
    body = (
        body.replace(r"\begin{threeparttable}", "")
        .replace(r"\end{threeparttable}", "")
        .replace(r"\begin{tabular}", r"\begin{adjustbox}{max width=\textwidth}" + "\n" + r"\begin{tabular}")
        .replace(r"\end{tabular}", r"\end{tabular}" + "\n" + r"\end{adjustbox}")
        .replace(r"\begin{tablenotes}[flushleft]\footnotesize",
                 r"\smallskip" + "\n" + r"\begin{minipage}{\linewidth}\footnotesize \emph{Notes.}")
        .replace(r"\item ", "")
        .replace(r"\end{tablenotes}", r"\end{minipage}")
    )
    (OUT_TAB / name).write_text(HEADER + body + "\n", encoding="utf-8")
    print(f"  wrote tables/{name}")


